// Writes src/emoji-data.ts from Unicode's emoji-test.txt (1126): every fully-qualified emoji
// without a skin tone, named after its CLDR short name ("grinning face" → grinning_face). A "~" before
// the name marks an emoji that takes a skin tone (1335); the client builds the toned character.
// Run: node scripts/emoji-data.mjs [path to emoji-test.txt]
import { readFile, writeFile } from "node:fs/promises";

const VERSION = "16.0"; // Apple, Google and Microsoft fonts all draw 16.0; 17.0 shows boxes on older systems
const src = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch(`https://unicode.org/Public/emoji/${VERSION}/emoji-test.txt`)).text();

const GROUPS = { "Smileys & Emotion": "people", "People & Body": "people", "Animals & Nature": "nature", "Food & Drink": "food", "Travel & Places": "travel", Activities: "activities", Objects: "objects", Symbols: "symbols", Flags: "flags" };
// Same as withTone in src/emoji.ts; checked below against every uniform-tone line in the file.
const MODS = ["\u{1F3FB}", "\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"];
const withTone = (ch, mod) => ch.replace(/(\u200D\u{1F91D})|(\p{Emoji_Modifier_Base})\uFE0F?/gu, (_, hands, base) => hands ?? base + mod);
const toned = new Set(src.match(/^[0-9A-F ]+; fully-qualified\s+# \S+/gm).map((l) => l.split("# ")[1]).filter((ch) => /[\u{1F3FB}-\u{1F3FF}]/u.test(ch)));
const covered = new Set();
const out = {};
const seen = new Set();
let group = "";
for (const line of src.split("\n")) {
  const g = line.match(/^# group: (.*)/);
  if (g) group = GROUPS[g[1]] ?? "";
  const m = line.match(/^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.*)$/);
  if (!m || !group || m[2].includes("skin tone")) continue;
  const name = m[2]
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/#/g, "hash")
    .replace(/\*/g, "asterisk")
    .replace(/[^a-z0-9+-]+/g, "_")
    .replace(/^_+|_+$/g, "");
  if (seen.has(name)) throw new Error(`duplicate name ${name}`);
  seen.add(name);
  const tones = MODS.map((mod) => withTone(m[1], mod));
  const takesTone = tones.every((t) => toned.has(t)); // families and 👯 are modifier bases without RGI toned forms
  if (takesTone) tones.forEach((t) => covered.add(t));
  (out[group] ??= []).push(takesTone ? `~${name}` : name, m[1]);
}
const missed = [...toned].filter((t) => !covered.has(t) && new Set(t.match(/[\u{1F3FB}-\u{1F3FF}]/gu)).size === 1);
if (missed.length) throw new Error(`withTone misses ${missed.join(" ")}`);
const body = Object.entries(out).map(([id, items]) => `  [${JSON.stringify(id)}, ${JSON.stringify(items.join(" "))}],`);
await writeFile(
  new URL("../src/emoji-data.ts", import.meta.url),
  `// Generated by scripts/emoji-data.mjs from Unicode emoji-test.txt ${VERSION}. Do not edit.\n// Per group: "name char name char ...". "~name" takes a skin tone (see withTone in emoji.ts).\nexport const EMOJI_DATA: [string, string][] = [\n${body.join("\n")}\n];\n`,
);
console.log(`${seen.size} emoji, ${covered.size / 5} take a skin tone`);
