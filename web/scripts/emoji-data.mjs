// Writes src/emoji-data.ts from Unicode's emoji-test.txt (1126): every fully-qualified emoji
// without a skin tone, named after its CLDR short name ("grinning face" → grinning_face).
// Run: node scripts/emoji-data.mjs [path to emoji-test.txt]
import { readFile, writeFile } from "node:fs/promises";

const VERSION = "16.0"; // Apple, Google and Microsoft fonts all draw 16.0; 17.0 shows boxes on older systems
const src = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch(`https://unicode.org/Public/emoji/${VERSION}/emoji-test.txt`)).text();

const GROUPS = { "Smileys & Emotion": "people", "People & Body": "people", "Animals & Nature": "nature", "Food & Drink": "food", "Travel & Places": "travel", Activities: "activities", Objects: "objects", Symbols: "symbols", Flags: "flags" };
const out = {};
const seen = new Set();
let group = "";
for (const line of src.split("\n")) {
  const g = line.match(/^# group: (.*)/);
  if (g) group = GROUPS[g[1]] ?? "";
  const m = line.match(/^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.*)$/);
  if (!m || !group || m[2].includes("skin tone")) continue;
  const name = m[2]
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/#/g, "hash")
    .replace(/\*/g, "asterisk")
    .replace(/[^a-z0-9+-]+/g, "_")
    .replace(/^_+|_+$/g, "");
  if (seen.has(name)) throw new Error(`duplicate name ${name}`);
  seen.add(name);
  (out[group] ??= []).push(name, m[1]);
}
const body = Object.entries(out).map(([id, items]) => `  [${JSON.stringify(id)}, ${JSON.stringify(items.join(" "))}],`);
await writeFile(
  new URL("../src/emoji-data.ts", import.meta.url),
  `// Generated by scripts/emoji-data.mjs from Unicode emoji-test.txt ${VERSION}. Do not edit.\n// Per group: "name char name char ...".\nexport const EMOJI_DATA: [string, string][] = [\n${body.join("\n")}\n];\n`,
);
console.log(`${seen.size} emoji`);
